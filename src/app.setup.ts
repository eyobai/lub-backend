import { INestApplication, ValidationPipe } from '@nestjs/common';
import type { NestExpressApplication } from '@nestjs/platform-express';
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger';
import helmet from 'helmet';
import { APP_CONFIG } from './config/configuration';
import type { AppConfig } from './config/configuration';

/** Shared by main.ts and the integration tests so both run the exact same HTTP pipeline. */
export function configureApp(app: INestApplication): AppConfig {
  const config = app.get<AppConfig>(APP_CONFIG);

  (app as NestExpressApplication).set('trust proxy', config.trustProxy);
  (app as NestExpressApplication).disable('x-powered-by');
  app.use(helmet());
  app.enableCors({ origin: config.corsOrigins.length ? config.corsOrigins : false, credentials: true });
  app.setGlobalPrefix(config.apiPrefix, { exclude: ['health', 'health/ready'] });
  app.useGlobalPipes(
    new ValidationPipe({
      whitelist: true,
      forbidNonWhitelisted: true,
      transform: true,
      stopAtFirstError: false,
      validationError: { target: false, value: false },
    }),
  );
  app.enableShutdownHooks();
  return config;
}

export function buildOpenApiDocument(app: INestApplication) {
  const builder = new DocumentBuilder()
    .setTitle('LUB Auction API')
    .setDescription(
      [
        'Backend API for the Lowest Unique Bid auction platform.',
        '',
        '**Conventions**',
        '- All monetary values are integers in minor units (santim for ETB) with an ISO-4217 `currency`.',
        '- All timestamps are ISO-8601 UTC and generated by the server.',
        '- Errors share one shape (`ErrorResponseDto`); `error` is a stable machine-readable code.',
        '- Protected endpoints need `Authorization: Bearer <accessToken>`.',
      ].join('\n'),
    )
    .setVersion('0.1.0')
    .addBearerAuth()
    .addTag('Authentication', 'Registration, phone verification, sign-in, tokens and password recovery')
    .addTag('Wallet', 'Balance and transaction history of the signed-in user')
    .addTag('Auctions', 'Public auction listing and details')
    .addTag('Bids', 'Placing bids and my bid history')
    .addTag('Admin: Products', 'Back-office product catalogue')
    .addTag('Admin: Auctions', 'Back-office auction setup and lifecycle')
    .addTag('Admin: Wallets', 'Back-office wallet views, manual adjustments, freezing and ledger reconciliation')
    .addTag('Health', 'Liveness and readiness probes')
    .build();
  return SwaggerModule.createDocument(app, builder);
}

export function setupSwagger(app: INestApplication): void {
  SwaggerModule.setup('docs', app, buildOpenApiDocument(app), {
    jsonDocumentUrl: 'docs/openapi.json',
    swaggerOptions: { persistAuthorization: true },
  });
}
